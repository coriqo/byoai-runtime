"""Write the extension's copy of the Shield design tokens.

    python scripts/gen_extension_tokens.py          # rewrite shield-tokens.css
    python scripts/gen_extension_tokens.py --check  # exit 1 when it is stale

`web/src/styles/tokens.css` is the single source of Shield's colours, type
scale, spacing, radii, shadows and icon sizes. The browser extension ships
without the web build, so its popup and welcome page link a copy of that file
from the extension folder. The copy is generated, never edited by hand, and a
test (tests/integrations/test_shield_tokens.py) fails when it is stale.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "web" / "src" / "styles" / "tokens.css"
TARGET = ROOT / "src" / "byoai" / "browser_extension" / "shield-tokens.css"
HEADER = (
    "/* GENERATED by scripts/gen_extension_tokens.py from web/src/styles/tokens.css.\n"
    "   Do not edit: change the source and run the script. */\n\n"
)


def render() -> str:
    return HEADER + SOURCE.read_text()


def main(argv: list[str]) -> int:
    want = render()
    if "--check" in argv:
        if not TARGET.exists() or TARGET.read_text() != want:
            print(f"{TARGET.relative_to(ROOT)} is stale: run python scripts/gen_extension_tokens.py")
            return 1
        return 0
    TARGET.write_text(want)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
