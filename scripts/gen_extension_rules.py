"""Write the browser extension's copy of Shield's rules: shield-rules.js.

    python scripts/gen_extension_rules.py

The extension replaces personal details in the page, before a message leaves
the browser, so it needs the same patterns the desktop proxy uses. They are
generated from ``byoai.integrations.shield`` rather than kept by hand, so the
two can't drift: ``tests/integrations/test_shield.py`` fails if the file on
disk is not what this script would write.
"""
from __future__ import annotations

import json
from pathlib import Path

from byoai.integrations.shield import extension_rules, rules_version_of

TARGET = (Path(__file__).resolve().parent.parent / "src" / "byoai"
          / "browser_extension" / "shield-rules.js")


def render() -> str:
    rules = extension_rules()
    # The version of the rules a file row names: a hash of everything above,
    # computed the same way in byoai.integrations.shield (RULES_VERSION).
    rules = {**rules, "rules_version": rules_version_of(rules)}
    body = json.dumps(rules, indent=2)
    return (
        "// GENERATED by scripts/gen_extension_rules.py from\n"
        "// byoai.integrations.shield. Do not edit; re-run the script.\n"
        "//\n"
        "// Page world, loaded before content.js: the rules content.js uses to\n"
        "// replace personal details before a message leaves the browser.\n"
        "(function () {\n"
        "  'use strict'\n"
        "  if (window.__shieldRules) return\n"
        f"  const rules = {body.replace(chr(10), chr(10) + '  ')}\n"
        "  Object.defineProperty(window, '__shieldRules', { value: Object.freeze(rules) })\n"
        "})()\n"
    )


SITES_SOURCE = TARGET.parent / "sites.json"
OPTIONAL_SOURCE = TARGET.parent / "optional_sites.json"
OPTIONAL_TARGET = TARGET.parent / "shield-optional.js"
MANIFEST = TARGET.parent / "manifest.json"


def optional_sites() -> list[dict]:
    """The curated origins an admin can switch on. The ONE list: the manifest's
    optional_host_permissions, shield-optional.js and the policy validator
    all derive from optional_sites.json."""
    return json.loads(OPTIONAL_SOURCE.read_text())["sites"]


def render_optional() -> str:
    hosts = [{"host": o["host"], "app": o["app"], "vendor": o["vendor"]}
             for o in optional_sites()]
    return (
        "// GENERATED by scripts/gen_extension_rules.py from optional_sites.json.\n"
        "// Do not edit. The origins an admin may switch on through Shield policy.\n"
        f"globalThis.SHIELD_OPTIONAL_SITES = {json.dumps(hosts, indent=2)}\n"
    )


def render_manifest() -> str:
    m = json.loads(MANIFEST.read_text())
    m["optional_host_permissions"] = [f"https://{o['host']}/*" for o in optional_sites()]
    return json.dumps(m, indent=2) + "\n"
SITES_TARGET = TARGET.parent / "shield-sites.js"


def render_sites() -> str:
    """shield-sites.js: sites.json as a script both worlds can read at
    document_start (a JSON file would need an async fetch)."""
    sites = json.loads(SITES_SOURCE.read_text())
    # Curated optional sites: the same shape, generic selectors, marked so the
    # gate knows an admin switches them on (see optional_sites.json).
    sites["sites"] = sites["sites"] + [
        {"app": o["app"], "hosts": [o["host"]], "compose": [], "send": [],
         "chat_paths": [], "upload": ["input[type=\"file\"]"], "optional": True}
        for o in optional_sites()]
    body = json.dumps(sites, indent=2)
    return (
        "// GENERATED by scripts/gen_extension_rules.py from sites.json.\n"
        "// Do not edit; change sites.json and re-run the script.\n"
        "//\n"
        "// Where each app's message box, send button and file input are: the input\n"
        "// gate's defaults. It falls back to generic selectors when these miss.\n"
        "(function () {\n"
        "  'use strict'\n"
        "  if (window.__shieldSites) return\n"
        f"  const sites = {body.replace(chr(10), chr(10) + '  ')}\n"
        "  Object.defineProperty(window, '__shieldSites', { value: Object.freeze(sites) })\n"
        "})()\n"
    )


# Chrome injects a given script file once per frame, even when two
# content_scripts entries list it, so the isolated world can't share files
# with the page world: it gets its own bundle of the rules, the site profiles
# and the engine (shield-core.js, which is hand-written and copied verbatim).
ISO_TARGET = TARGET.parent / "shield-iso.js"
CORE_SOURCE = TARGET.parent / "shield-core.js"


def render_iso() -> str:
    return (
        "// GENERATED by scripts/gen_extension_rules.py: shield-rules.js,\n"
        "// shield-sites.js and shield-core.js for the extension's isolated world\n"
        "// (Chrome won't inject the same file into both worlds). Do not edit.\n"
        + render() + ";\n" + render_sites() + ";\n" + CORE_SOURCE.read_text()
    )


def main() -> None:
    TARGET.write_text(render())
    print(f"wrote {TARGET}")
    SITES_TARGET.write_text(render_sites())
    print(f"wrote {SITES_TARGET}")
    OPTIONAL_TARGET.write_text(render_optional())
    print(f"wrote {OPTIONAL_TARGET}")
    MANIFEST.write_text(render_manifest())
    print(f"wrote {MANIFEST}")
    ISO_TARGET.write_text(render_iso())
    print(f"wrote {ISO_TARGET}")


if __name__ == "__main__":
    main()
